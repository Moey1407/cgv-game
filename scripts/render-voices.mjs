// Generate original character performances for local playback.
// Requires edge-tts installed in work/voice-tools (ignored by git).
import { spawn } from 'node:child_process';
import { mkdir, stat, writeFile, rename } from 'node:fs/promises';
import { resolve } from 'node:path';
import { voiceLines, CINEMATICS, DEX, WREN } from '../src/story.js';
import { RECORDED_TEXT } from '../src/voiceManifest.js';

const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'public/audio/voice');
const tools = resolve(root, 'work/voice-tools');
const jobs = [
  ...voiceLines().filter((line) => line.who === DEX || line.who === WREN).map((line) => ({ ...line })),
  ...Object.entries(CINEMATICS).flatMap(([key, frames]) => frames.flatMap((frame, index) =>
    frame.dialogue ? [{ id: `cinematic-${key}-${index + 1}`, who: frame.speaker, text: frame.dialogue }] : [])),
  { id: 'voice-test', who: DEX, text: 'Comms check. If you can hear me, the radio is working.' },
];

await mkdir(output, { recursive: true });
const performance = {
  [DEX]: { voice: 'en-GB-RyanNeural', rate: '-5%', pitch: '-9Hz' },
  [WREN]: { voice: 'en-GB-SoniaNeural', rate: '-3%', pitch: '-2Hz' },
};

function render(job) {
  const actor = performance[job.who];
  const target = resolve(output, `${job.id}.candidate.mp3`);
  return new Promise((done, fail) => {
    // Windows ships `python`; macOS and Linux usually only have `python3`. Override with PYTHON=...
    const python = process.env.PYTHON ?? (process.platform === 'win32' ? 'python' : 'python3');
    const child = spawn(python, [
      '-m', 'edge_tts', '--voice', actor.voice, `--rate=${actor.rate}`, `--pitch=${actor.pitch}`,
      '--text', job.text, '--write-media', target,
    ], { cwd: root, env: { ...process.env, PYTHONPATH: tools }, windowsHide: true });
    let error = '';
    child.stderr.on('data', (data) => { error += data.toString(); });
    child.on('error', fail);
    child.on('close', (code) => code === 0 ? done(target) : fail(new Error(`${job.id}: ${error || `exit ${code}`}`)));
  });
}

let next = 0;
const failures = [];
const recorded = { ...RECORDED_TEXT };
async function worker() {
  while (next < jobs.length) {
    const job = jobs[next++];
    const target = resolve(output, `${job.id}.mp3`);
    try {
      if ((await stat(target).catch(() => null))?.size > 0 && recorded[job.id] === job.text) continue;
      await render(job);
      await rename(resolve(output, `${job.id}.candidate.mp3`), target);
      recorded[job.id] = job.text;
      process.stdout.write(`Rendered ${job.id}\n`);
    } catch (error) {
      failures.push(String(error));
    }
  }
}

await Promise.all([worker(), worker(), worker()]);
const available = [];
for (const id of Object.keys(recorded)) if ((await stat(resolve(output, `${id}.mp3`)).catch(() => null))?.size > 0) available.push(id);
await writeFile(resolve(root, 'src/voiceManifest.js'),
  `// Generated by scripts/render-voices.mjs. Audio stays in public/audio/voice.\nexport const RECORDED_CLIPS = ${JSON.stringify(available, null, 2)};\nexport const RECORDED_TEXT = ${JSON.stringify(Object.fromEntries(available.map((id) => [id, recorded[id]])), null, 2)};\n`);
process.stdout.write(`Finished ${available.length}/${jobs.length} clips.\n`);
if (failures.length) {
  process.stderr.write(failures.join('\n') + '\n');
  process.exitCode = 1;
}
